import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { createServer } from 'vite';
const server = await createServer({ server: { host: '127.0.0.1', port: 0, open: false, strictPort: false } });
await server.listen();
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
try {
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}`, { waitUntil: 'networkidle' });
  await page.locator('#play-button:enabled').click();
  await page.waitForFunction(() => document.body.dataset.started === 'true');
  await page.evaluate(async () => {
    const source = performance.getEntriesByType('resource').find((entry) => entry.name.includes('/js/main.js')).name;
    window.testApp = (await import(source)).experience;
  });
  const first = await page.evaluate(() => testApp.scene.film.rotation.y);
  await page.waitForTimeout(700);
  assert.ok(await page.evaluate(() => testApp.scene.film.rotation.y) < first, 'Playback must start without another click');
  const hoverBox = await page.locator('.film-ring-frame.is-active .film-project-card').boundingBox();
  await page.mouse.move(hoverBox.x + hoverBox.width / 2, hoverBox.y + hoverBox.height / 2);
  await page.waitForTimeout(550);
  const hovered = await page.evaluate(() => testApp.scene.film.rotation.y);
  await page.waitForTimeout(350);
  assert.ok(Math.abs(await page.evaluate(() => testApp.scene.film.rotation.y) - hovered) < 0.001, 'Hover must pause automatic rotation');
  await page.mouse.move(15, 15);
  await page.waitForTimeout(550);
  assert.ok(await page.evaluate(() => testApp.scene.film.rotation.y) < hovered, 'Mouse leave must resume automatic rotation');
  await page.evaluate(() => testApp.story.setPlaying(false));
  await page.waitForTimeout(500);
  const paused = await page.evaluate(() => testApp.scene.film.rotation.y);
  await page.mouse.move(20, 300);
  await page.mouse.wheel(0, 180);
  await page.waitForTimeout(700);
  assert.equal(await page.evaluate(() => testApp.scene.film.rotation.y), paused, 'Scrolling the page must not rotate a paused reel');
  await page.evaluate(() => testApp.story.goToFrame(0));
  await page.waitForTimeout(800);
  const poster = page.locator('.film-ring-frame.is-active .frame-media');
  const rect = await poster.boundingBox();
  const angle = await page.evaluate(() => testApp.scene.film.rotation.y);
  await page.mouse.move(rect.x + rect.width * 0.5, rect.y + rect.height * 0.5);
  await page.mouse.down();
  await page.mouse.move(rect.x + rect.width * 0.5 - 140, rect.y + rect.height * 0.5, { steps: 14 });
  await page.mouse.up();
  await page.waitForTimeout(900);
  assert.ok(Math.abs(await page.evaluate(() => testApp.scene.film.rotation.y) - angle) > 0.3, 'Dragging must rotate and select a frame');
  assert.equal(await page.locator('#phone-viewer').getAttribute('aria-hidden'), 'true', 'Dragging must not open the gallery');
  await page.locator('nav [data-chapter="sites"]').click();
  await page.waitForTimeout(1300);
  assert.equal(await page.locator('body').getAttribute('data-chapter'), 'sites');
  await page.locator('nav [data-chapter="about"]').click();
  await page.waitForTimeout(1300);
  assert.ok(await page.locator('.photo-shell-edge').count() >= 4);
  await page.screenshot({ path: 'logs/REFINO-FOTO.png' });
  await page.locator('nav [data-chapter="contact"]').click();
  await page.waitForTimeout(1300);
  assert.ok(await page.locator('.vhs-shell-edge').count() >= 4);
  await page.screenshot({ path: 'logs/REFINO-VHS.png' });
  await page.locator('nav [data-chapter="projects"]').click();
  await page.waitForTimeout(1300);
  await page.evaluate(() => testApp.story.setPlaying(true));
  await page.mouse.move(15, 15);
  const resume = await page.evaluate(() => testApp.scene.film.rotation.y);
  await page.waitForTimeout(700);
  assert.ok(await page.evaluate(() => testApp.scene.film.rotation.y) < resume, 'Playback must resume after selection without jumping backward');
  await page.screenshot({ path: 'logs/REFINO-FITA.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(500);
  await page.locator('nav [data-chapter="sites"]').click();
  await page.waitForTimeout(1600);
  await page.screenshot({ path: 'logs/REFINO-MOBILE-SITES.png' });
  assert.deepEqual(errors, []);
  console.log('PASS: automatic rotation, pause, independent scroll, pointer drag, snap selection, no accidental modal, physical 3D shells, chapter flights, resume and mobile.');
} finally {
  await browser.close();
  await server.close();
}
